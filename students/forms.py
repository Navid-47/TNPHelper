"""
Forms for student profile management and resume upload.
(Registration and login forms are in accounts/forms.py)
"""
from django import forms
from django.conf import settings
from django.core.exceptions import ValidationError
from .models import Student
import os


class StudentProfileForm(forms.ModelForm):
    """Form for updating student profile information."""

    class Meta:
        model = Student
        fields = ['name', 'branch', 'cgpa', 'skills', 'placement_status', 'company_name', 'package']
        widgets = {
            'name': forms.TextInput(attrs={'class': 'form-control'}),
            'branch': forms.Select(attrs={'class': 'form-control'}),
            'cgpa': forms.NumberInput(attrs={
                'class': 'form-control',
                'step': '0.01',
                'min': '0.0',
                'max': '10.0'
            }),
            'skills': forms.Textarea(attrs={
                'class': 'form-control',
                'rows': 3,
                'placeholder': 'Enter skills separated by commas'
            }),
            'placement_status': forms.Select(attrs={'class': 'form-control'}),
            'company_name': forms.TextInput(attrs={
                'class': 'form-control',
                'placeholder': 'Enter company name (if placed)'
            }),
            'package': forms.NumberInput(attrs={
                'class': 'form-control',
                'step': '0.01',
                'min': '0.0',
                'placeholder': 'Package in LPA'
            }),
        }

    def clean_package(self):
        """Package is required when placed."""
        package = self.cleaned_data.get('package')
        placement_status = self.cleaned_data.get('placement_status')
        if placement_status == 'placed' and not package:
            raise ValidationError('Package is required when placement status is "Placed".')
        return package

    def clean_company_name(self):
        """Company name is required when placed."""
        company_name = self.cleaned_data.get('company_name')
        placement_status = self.cleaned_data.get('placement_status')
        if placement_status == 'placed' and not company_name:
            raise ValidationError('Company name is required when placement status is "Placed".')
        return company_name


# PDF magic bytes: every valid PDF starts with %PDF
_PDF_MAGIC = b'%PDF'


class ResumeUploadForm(forms.ModelForm):
    """Form for uploading a PDF resume file."""

    class Meta:
        model = Student
        fields = ['resume']
        widgets = {
            'resume': forms.FileInput(attrs={
                'class': 'form-control',
                'accept': '.pdf'
            })
        }

    def clean_resume(self):
        """
        Validate resume upload with multiple layers of defence:
            1. File must not be empty.
            2. Extension must be .pdf (case-insensitive).
            3. Content-Type (MIME) must be application/pdf.
            4. Magic bytes must start with %PDF.
            5. File size must not exceed settings.MAX_RESUME_SIZE.
        The server-side filename is generated by student_resume_path (UUID)
        so the user-supplied name is never trusted for storage.
        """
        resume = self.cleaned_data.get('resume')
        if not resume:
            return resume

        # 1. Reject empty files
        if resume.size == 0:
            raise ValidationError('The uploaded file is empty.')

        # 2. Check file extension
        ext = os.path.splitext(resume.name)[1].lower()
        if ext != '.pdf':
            raise ValidationError('Only PDF files are allowed. Please upload a .pdf file.')

        # 3. Check MIME / content-type header sent by the browser
        content_type = getattr(resume, 'content_type', '')
        if content_type and content_type not in ('application/pdf', 'application/x-pdf'):
            raise ValidationError('Only PDF files are allowed (invalid content type).')

        # 4. Check magic bytes (%PDF) — cannot be faked by renaming
        resume.seek(0)
        header = resume.read(4)
        resume.seek(0)
        if header != _PDF_MAGIC:
            raise ValidationError(
                'The file does not appear to be a valid PDF. '
                'Please upload a genuine PDF document.'
            )

        # 5. Enforce max size from settings (default 5 MB)
        max_size = getattr(settings, 'MAX_RESUME_SIZE', 5 * 1024 * 1024)
        if resume.size > max_size:
            max_mb = max_size // (1024 * 1024)
            raise ValidationError(
                f'Resume file size must be less than {max_mb} MB. '
                f'Your file is {resume.size // (1024 * 1024)} MB.'
            )

        return resume